        private const uint ZrifDictId = 0x627D1D5DU;

        public static byte[] Decode(string zrif)
        {
            if (string.IsNullOrWhiteSpace(zrif)) throw new ArgumentException("zrif is empty.", nameof(zrif));

            string s = zrif.Trim();
            s = s.Replace('-', '+').Replace('_', '/');
            int pad = s.Length % 4;
            if (pad != 0) s += new string('=', 4 - pad);

            byte[] zstream;
            try { zstream = Convert.FromBase64String(s); }
            catch (FormatException ex) { throw new FormatException("zrif is not valid base64.", ex); }

            if (zstream.Length < 2 + 4) throw new FormatException("zrif payload too short.");

            byte cmf = zstream[0];
            byte flg = zstream[1];
            if ((((cmf << 8) | flg) % 31) != 0) throw new FormatException("zrif: invalid zlib header checksum.");
            if ((cmf & 0x0F) != 8)              throw new FormatException("zrif: unsupported compression method (expected deflate).");
            bool fdict = (flg & 0x20) != 0;

            int hdrLen = 2;
            if (fdict)
            {
                if (zstream.Length < 6 + 4) throw new FormatException("zrif payload truncated.");
                uint dictId = ((uint)zstream[2] << 24) | ((uint)zstream[3] << 16) | ((uint)zstream[4] << 8) | zstream[5];
                if (dictId != ZrifDictId) throw new FormatException(string.Format("zrif: unknown dictionary id 0x{0:X8}.", dictId));
                hdrLen = 6;
            }

            int deflateLen = zstream.Length - hdrLen - 4; // last 4 bytes are the Adler32 trailer
            if (deflateLen <= 0) throw new FormatException("zrif: no deflate payload.");

            // Wrap: stored block holding the dictionary, then the original deflate bitstream.
            //
            // Stored block layout (RFC 1951 §3.2.4):
            //   3 bits header: BFINAL (1 bit, 0 here so the original blocks continue), BTYPE
            //                  (2 bits, 0b00 for stored)
            //   bits padded to next byte boundary
            //   2 bytes LEN     little-endian
            //   2 bytes ~LEN    little-endian
            //   LEN bytes of literal data
            // We sit at bit 0 of byte 0, so the 3-bit header sits in the low 3 bits of byte 0
            // and the remaining 5 padding bits are also 0 → first byte is just 0x00.
            int dictLen = mZrifDict.Length;
            int notDict = (~dictLen) & 0xFFFF;
            byte[] wrapped = new byte[5 + dictLen + deflateLen];
            int w = 0;
            wrapped[w++] = 0x00;
            wrapped[w++] = (byte)(dictLen & 0xFF);
            wrapped[w++] = (byte)((dictLen >> 8) & 0xFF);
            wrapped[w++] = (byte)(notDict & 0xFF);
            wrapped[w++] = (byte)((notDict >> 8) & 0xFF);
            Buffer.BlockCopy(mZrifDict, 0, wrapped, w, dictLen);
            w += dictLen;
            Buffer.BlockCopy(zstream, hdrLen, wrapped, w, deflateLen);

            byte[] inflated;
            using (var src = new MemoryStream(wrapped))
            using (var dst = new MemoryStream())
            {
                // DeflateStream is raw-deflate-only — exactly what we built.
                using (var inf = new DeflateStream(src, CompressionMode.Decompress))
                {
                    inf.CopyTo(dst);
                }
                inflated = dst.ToArray();
            }

            if (inflated.Length <= dictLen)
                throw new FormatException(string.Format("zrif: inflated output ({0} bytes) is no larger than the dictionary ({1} bytes).", inflated.Length, dictLen));

            byte[] rif = new byte[inflated.Length - dictLen];
            Buffer.BlockCopy(inflated, dictLen, rif, 0, rif.Length);
            return rif;
        }

