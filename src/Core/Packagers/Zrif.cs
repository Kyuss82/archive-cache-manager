 *
 * zRIF → RIF decoder.
 *
 * zRIF is the compact form NoPayStation publishes for PSV NPDRM licenses:
 *   base64 (standard or URL-safe, no padding) → zlib stream with a 1024-byte
 *   preset dictionary (DICTID = 0x627D1D5D) → RIF blob (typically 0x200 bytes,
 *   the file Vita3K reads from ux0:license/app/&lt;TITLE_ID&gt;/&lt;contentid&gt;.rif).
 *
 * .NET's System.IO.Compression does not expose `inflateSetDictionary`, so we
 * can't hand the preset dictionary to a `ZLibStream`. We sidestep that with a
 * dictionary-replay trick:
 *
 *   1. Strip the zlib envelope (CMF/FLG + DICTID + trailing Adler32) to get the
 *      bare deflate bitstream that produced the RIF.
 *   2. Build a NEW raw-deflate bitstream that starts with a STORED block
 *      containing the 1024-byte preset dictionary verbatim, followed by the
 *      original bitstream.
 *   3. Run that through `DeflateStream(Decompress)`. The output is
 *      `dict || RIF` — the inflater "sees" the dict as already-emitted output
 *      and resolves back-references inside the RIF stream against it exactly
 *      like a real preset-dict decoder would.
 *   4. Slice off the first 1024 bytes; what remains is the RIF.
 *
 * No external dependency (we used SharpZipLib for a moment in v2.33 because of
 * its `Inflater.SetDictionary`, but on framework-dependent deploys the .NET
 * host fails to resolve transitive package files outside the NuGet cache).
 *
 * Reference for the dictionary: pkg2zip (mmozeiko/pkg2zip), MIT-licensed —
 * same 1024 bytes, same DICTID.
 */
using System;
using System.IO;
using System.IO.Compression;

